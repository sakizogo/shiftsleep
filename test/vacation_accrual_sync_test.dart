import 'package:flutter_test/flutter_test.dart';
import 'package:shiftsleep/models/vacation_model.dart';
import 'package:shiftsleep/repositories/vacation_repository.dart';

// N165 1/3：planAccrualSync（自動生成の付与の合わせ直しの計画）のテスト
// 予定は日付を決め打ちで渡す（3 だけ accrualsUntilToday も使う）

/// 自動生成の付与の行（notes は autoGenerateAccruals と同じ）
VacationAccrual autoAccrual(int year, int month, int day, double days) {
  return VacationAccrual.create(
    userId: 'test_user',
    accrualDate: DateTime(year, month, day),
    daysGranted: days,
    notes: VacationRepository.autoAccrualNotes(DateTime(year, month, day)),
  );
}

/// 自動生成でない付与の行
VacationAccrual otherAccrual(int year, int month, int day, double days, String? notes) {
  return VacationAccrual.create(
    userId: 'test_user',
    accrualDate: DateTime(year, month, day),
    daysGranted: days,
    notes: notes,
  );
}

({DateTime date, int days}) scheduled(int year, int month, int day, int days) =>
    (date: DateTime(year, month, day), days: days);

void main() {
  test('1. 初回付与日が変わった → 古い日付の自動生成の行を消し、新しい日付を足す', () {
    final old1 = autoAccrual(2024, 10, 1, 10);
    final old2 = autoAccrual(2025, 10, 1, 11);
    final plan = VacationRepository.planAccrualSync(
      existing: [old2, old1],
      schedule: [scheduled(2024, 10, 2, 10), scheduled(2025, 10, 2, 11)],
    );
    expect(plan.toDelete, [old1, old2]);  // N165 3a：古い順
    expect(plan.toAdd, [scheduled(2024, 10, 2, 10), scheduled(2025, 10, 2, 11)]);
  });

  test('1\'. N165 の再現（10/1 と 10/2 の両方がある）→ 10/1 の 2 行だけ消し、足すものはない', () {
    final old1 = autoAccrual(2024, 10, 1, 10);
    final old2 = autoAccrual(2025, 10, 1, 11);
    final new1 = autoAccrual(2024, 10, 2, 10);
    final new2 = autoAccrual(2025, 10, 2, 11);
    final plan = VacationRepository.planAccrualSync(
      existing: [new2, old2, new1, old1],
      schedule: [scheduled(2024, 10, 2, 10), scheduled(2025, 10, 2, 11)],
    );
    expect(plan.toDelete, [old1, old2]);  // N165 3a：古い順
    expect(plan.toAdd, isEmpty);
  });

  test('2. すべて一致 → 消す 0 件・足す 0 件', () {
    final plan = VacationRepository.planAccrualSync(
      existing: [autoAccrual(2025, 10, 1, 11), autoAccrual(2024, 10, 1, 10)],
      schedule: [scheduled(2024, 10, 1, 10), scheduled(2025, 10, 1, 11)],
    );
    expect(plan.toDelete, isEmpty);
    expect(plan.toAdd, isEmpty);
  });

  test('2\'. 時刻つき・Z つきの行も年月日が同じなら一致 → 消す 0 件・足す 0 件', () {
    final utcRow = VacationAccrual.fromMap(
      autoAccrual(2024, 10, 1, 10).toMap()..['accrual_date'] = '2024-10-01T00:00:00.000Z',
    );
    final timedRow = VacationAccrual.fromMap(
      autoAccrual(2025, 10, 1, 11).toMap()..['accrual_date'] = '2025-10-01T09:30:00.000',
    );
    final plan = VacationRepository.planAccrualSync(
      existing: [utcRow, timedRow],
      schedule: [scheduled(2024, 10, 1, 10), scheduled(2025, 10, 1, 11)],
    );
    expect(plan.toDelete, isEmpty);
    expect(plan.toAdd, isEmpty);
  });

  test('2\'\'. 日数が違っても日付が合っていれば消さず・足さない（日数は直さない）', () {
    final plan = VacationRepository.planAccrualSync(
      existing: [autoAccrual(2024, 10, 1, 15)],
      schedule: [scheduled(2024, 10, 1, 10)],
    );
    expect(plan.toDelete, isEmpty);
    expect(plan.toAdd, isEmpty);
  });

  test('3. 初回付与日が未来 → 予定は空で、自動生成の行はすべて消える', () {
    final now = DateTime.now();
    final future = DateTime(now.year + 1, now.month, now.day);
    final schedule = VacationRepository.accrualsUntilToday(future);
    expect(schedule, isEmpty);

    final a1 = autoAccrual(2024, 10, 1, 10);
    final a2 = autoAccrual(2025, 10, 1, 11);
    final plan = VacationRepository.planAccrualSync(
      existing: [a2, a1],
      schedule: schedule,
    );
    expect(plan.toDelete, [a1, a2]);  // N165 3a：古い順
    expect(plan.toAdd, isEmpty);
  });

  test('4. 自動生成でない行は消さず、その日付には足さない', () {
    final manual = otherAccrual(2024, 10, 1, 10, '手入力');
    final noNotes = otherAccrual(2023, 10, 1, 10, null);
    final plan = VacationRepository.planAccrualSync(
      existing: [manual, noNotes],
      schedule: [scheduled(2024, 10, 1, 11), scheduled(2025, 10, 1, 12)],
    );
    expect(plan.toDelete, isEmpty);
    expect(plan.toAdd, [scheduled(2025, 10, 1, 12)]);
  });

  test('5. autoAccrualNotes は今の notes と同じ文字列。isAutoGeneratedAccrual で見分けられる', () {
    expect(VacationRepository.autoAccrualNotes(DateTime(2025, 10, 2)), '自動生成：2025年度付与');
    expect(VacationRepository.isAutoGeneratedAccrual(autoAccrual(2025, 10, 2, 11)), isTrue);
    expect(VacationRepository.isAutoGeneratedAccrual(otherAccrual(2025, 10, 2, 11, '手入力')), isFalse);
    expect(VacationRepository.isAutoGeneratedAccrual(otherAccrual(2025, 10, 2, 11, null)), isFalse);
  });

  test('P6. 既存を新しい順（DB の読み順）で渡しても、消す行は付与日の古い順。同じ日付なら id 順', () {
    // 同じ日付の行は id を決め打ちにする。時刻が遅くても id が小さい行が先（年月日だけで比べる）
    VacationAccrual withId(String id, DateTime accrualDate) => VacationAccrual(
          id: id,
          userId: 'test_user',
          accrualDate: accrualDate,
          daysGranted: 10,
          expiryDate: VacationAccrual.calculateExpiryDate(accrualDate),
          notes: VacationRepository.autoAccrualNotes(accrualDate),
          createdAt: DateTime(2026, 1, 1),
          updatedAt: DateTime(2026, 1, 1),
        );
    final d2023 = autoAccrual(2023, 10, 1, 10);
    final b2024 = withId('b', DateTime(2024, 10, 1));
    final a2024 = withId('a', DateTime(2024, 10, 1, 9));
    final d2025 = autoAccrual(2025, 10, 1, 11);
    final plan = VacationRepository.planAccrualSync(
      existing: [d2025, b2024, a2024, d2023],
      schedule: [scheduled(2024, 10, 2, 10)],
    );
    expect(plan.toDelete, [d2023, a2024, b2024, d2025]);
    expect(plan.toAdd, [scheduled(2024, 10, 2, 10)]);
  });
}
